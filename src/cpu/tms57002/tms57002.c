static UINT32 aacc, xoa, xba, xwr, xrd, txrd, creg;

static UINT8 pc, hpc, ca, id, ba0, ba1, rptc, rptc_next, sa;

static UINT32 xm_adr;

static UINT8 host[4], hidx, allow_update;

static UINT32 update[16];
static UINT8 update_counter_head, update_counter_tail;

static cd cache;

static UINT32 tms_pram[256];			/* program RAM */
static UINT8 tms_dram[0x40000];		/* data RAM on the board */
static int icount;

static void (*empty_callback)( int state );

/* memory */

static UINT8 data_read_byte( UINT32 adr )
{
	return adr < sizeof( tms_dram ) ? tms_dram[ adr ] : 0;
}

static void data_write_byte( UINT32 adr, UINT8 v )
{
	if( adr < sizeof( tms_dram ) )
		tms_dram[ adr ] = v;
}

/* host port lines */

static void update_dready( void )
{
}

static void update_pc0( void )
{
}

static void update_empty( void )
{
	if( empty_callback )
		empty_callback( update_counter_head == update_counter_tail );
}

void tms57002dsp_set_empty_callback( void (*callback)( int state ) )
{
	empty_callback = callback;
}

void tms57002dsp_pload_w( int state )
{
	UINT8 olds = sti;
	if (state)
		sti &= ~IN_PLOAD;
	else
		sti |= IN_PLOAD;
	if (olds ^ sti)
	{
		if (sti & IN_PLOAD)
		{
			hidx = 0;
			pc = 0;
			ca = 0;
			sti &= ~(SU_MASK);
		}
	}
}

void tms57002dsp_cload_w( int state )
{
	UINT8 olds = sti;
	if (state)
		sti &= ~IN_CLOAD;
	else
		sti |= IN_CLOAD;
	if (olds ^ sti)
	{
		if (sti & IN_CLOAD)
		{
			hidx = 0;
			/* ca = 0; seems extremely dubious */
		}
	}
}

static void cache_flush( void );

void tms57002dsp_reset( void )
{
	sti = (sti & ~(SU_MASK|S_READ|S_WRITE|S_BRANCH|S_HOST|S_UPDATE)) | (SU_ST0|S_IDLE);
	pc = 0;
	ca = 0;
	hidx = 0;
	id = 0;
	ba0 = 0;
	ba1 = 0;
	sa = 0;
	rptc = 0;
	rptc_next = 0;
	update_counter_tail = 0;
	update_counter_head = 0;
	st0 &= ~(ST0_INCS | ST0_DIRI | ST0_FI | ST0_SIM | ST0_PLRI |
			ST0_PBCI | ST0_DIRO | ST0_FO | ST0_SOM | ST0_PLRO |
			ST0_PBCO | ST0_CNS);
	st1 &= ~(ST1_AOV | ST1_SFAI | ST1_SFAO | ST1_AOVM | ST1_MOVM | ST1_MOV |
			ST1_SFMA | ST1_SFMO | ST1_RND | ST1_CRM | ST1_DBP);
	update_dready();
	update_pc0();
	update_empty();

	xba = 0;
	xoa = 0;
	cache_flush();
}

void tms57002dsp_data_w( UINT8 data )
{
	UINT32 val;
	switch (sti & (IN_PLOAD|IN_CLOAD))
	{
	case 0:
		hidx = 0;
		sti &= ~SU_CVAL;
		break;
	case IN_PLOAD:
		host[hidx++] = data;
		if (hidx >= 3)
		{
			val = (host[0]<<16) | (host[1]<<8) | host[2];
			hidx = 0;

			switch (sti & SU_MASK)
			{
			case SU_ST0:
				st0 = val;
				sti = (sti & ~SU_MASK) | SU_ST1;
				break;
			case SU_ST1:
				st1 = val;
				sti = (sti & ~SU_MASK) | SU_PRG;
				break;
			case SU_PRG:
				tms_pram[pc++] = val;
				update_pc0();
				break;
			}
		}
		break;
	case IN_CLOAD:
		if (sti & SU_CVAL)
		{
			host[hidx++] = data;
			if (hidx >= 4)
			{
				val = ((UINT32)host[0]<<24) | (host[1]<<16) | (host[2]<<8) | host[3];
				sti &= ~SU_CVAL;
				update[update_counter_head] = val;
				update_counter_head = (update_counter_head + 1) & 0x0f;
				hidx = 1; /* the write shouldn't really happen until CLOAD is high though */
				update_empty();
			}
		}
		else
		{
			sa = data;
			hidx = 0;
			sti |= SU_CVAL;
		}

		break;
	case IN_PLOAD|IN_CLOAD:
		host[hidx++] = data;
		if (hidx >= 4)
		{
			val = ((UINT32)host[0]<<24) | (host[1]<<16) | (host[2]<<8) | host[3];
			hidx = 0;
			cmem[ca++] = val;
		}
		break;
	};
}

UINT8 tms57002dsp_data_r( void )
{
	UINT8 res;
	if (!(sti & S_HOST))
		return 0xff;

	res = host[hidx];
	hidx++;
	if (hidx == 4)
	{
		hidx = 0;
		sti &= ~S_HOST;
		update_dready();
	}

	return res;
}

int tms57002dsp_fifo_count( void )
{
	return ( update_counter_head - update_counter_tail ) & 0x0f;
}

int tms57002dsp_empty_r( void )
{
	return (update_counter_head == update_counter_tail);
}

static void sync_w( int state )
{
	if (sti & (IN_PLOAD /*| IN_CLOAD*/))
		return;

	allow_update = 1;
	pc = 0;
	ca = 0;
	id = 0;
	if (!(st0 & ST0_INCS))
	{
		ba0--;
		ba1++;
	}
	xba = (xba-1) & 0x7ffff;
	st1 &= ~(ST1_AOV | ST1_MOV);
	sti &= ~S_IDLE;
}

static void xm_init( void )
{
	UINT32 adr = xoa + xba;
	UINT32 mask = 0;

	switch (st0 & ST0_M)
	{
	case ST0_M_64K:  mask = 0x0ffff; break;
	case ST0_M_256K: mask = 0x3ffff; break;
	case ST0_M_1M:   mask = 0xfffff; break;
	}
	if (st0 & ST0_WORD)
		adr <<= 2;
	else
		adr <<= 1;

	if (!(st0 & ST0_SEL))
		adr <<= 1;

	xm_adr = adr & mask;
}

static void xm_step_read( void )
{
	UINT32 adr = xm_adr;
	UINT8 v = data_read_byte(adr);
	int done, off;
	if (st0 & ST0_WORD)
	{
		if (st0 & ST0_SEL)
		{
			off = 16 - ((adr & 3) << 3);
			txrd = (txrd & ~(0xff << off)) | (v << off);
			done = off == 0;
		}
		else
		{
			off = 20 - ((adr & 7) << 2);
			txrd = (txrd & ~(0xf << off)) | ((v & 0xf) << off);
			done = off == 0;
		}
	}
	else
	{
		if (st0 & ST0_SEL)
		{
			off = 16 - ((adr & 1) << 3);
			txrd = (txrd & ~(0xff << off)) | (v << off);
			done = off == 8;
			if (done)
				txrd &= 0xffff00;
		}
		else
		{
			off = 20 - ((adr & 3) << 2);
			txrd = (txrd & ~(0xf << off)) | ((v & 0xf) << off);
			done = off == 8;
			if (done)
				txrd &= 0xffff00;
		}
	}
	if (done)
	{
		xrd = txrd;
		sti &= ~S_READ;
		xm_adr = 0;
	}
	else
		xm_adr = adr+1;
}

static void xm_step_write( void )
{
	UINT32 adr = xm_adr;
	UINT8 v;
	int done, off;
	if (st0 & ST0_WORD)
	{
		if (st0 & ST0_SEL)
		{
			off = 16 - ((adr & 3) << 3);
			v = xwr >> off;
			done = off == 0;
		}
		else
		{
			off = 20 - ((adr & 7) << 2);
			v = (xwr >> off) & 0xf;
			done = off == 0;
		}
	}
	else
	{
		if (st0 & ST0_SEL)
		{
			off = 16 - ((adr & 1) << 3);
			v = xwr >> off;
			done = off == 8;
		}
		else
		{
			off = 20 - ((adr & 3) << 2);
			v = (xwr >> off) & 0xf;
			done = off == 8;
		}
	}
	data_write_byte(adr, v);
	if (done)
	{
		sti &= ~S_WRITE;
		xm_adr = 0;
	}
	else
		xm_adr = adr+1;
}

/* the macc to output conversions (shift by sfmo, then optional saturation) */
#define MACC_M1_0	TMS_U64(0x000f8000, 0x00000000)
#define MACC_M1_1	TMS_U64(0x000fe000, 0x00000000)
#define MACC_M1_2	TMS_U64(0x000ff800, 0x00000000)
#define MACC_SIGN	TMS_U64(0x00080000, 0x00000000)
#define MACC_SATN	TMS_U64(0xffff8000, 0x00000000)
#define MACC_SATP	TMS_U64(0x00007fff, 0xffffffff)

static INT64 macc_to_output( INT64 rounding, UINT64 rmask, int shift, int saturate )
{
	INT64 m = macc_read;
	UINT64 m1;
	int over = 0;

	/* overflow detection and shifting */
	switch( shift )
	{
	case 0:
		m1 = m & MACC_M1_0;
		if (m1 && m1 != MACC_M1_0)
			over = 1;
		break;
	case 1:
		m1 = m & MACC_M1_1;
		if (m1 && m1 != MACC_M1_1)
			over = 1;
		m <<= 2;
		break;
	case 2:
		m1 = m & MACC_M1_2;
		if (m1 && m1 != MACC_M1_2)
			over = 1;
		m <<= 4;
		break;
	case 3:
		m >>= 8;
		break;
	}

	m = (m + rounding) & rmask;

	/* second overflow detection */
	m1 = m & MACC_M1_0;
	if (m1 && m1 != MACC_M1_0)
		over = 1;

	/* overflow handling */
	if (over)
	{
		st1 |= ST1_MOV;
		if (saturate)
		{
			if (m & MACC_SIGN)
				m = MACC_SATN;
			else
				m = MACC_SATP;
		}
	}
	return m;
}

#define macc_to_output_0(r, m)	macc_to_output( r, m, 0, 0 )
#define macc_to_output_1(r, m)	macc_to_output( r, m, 1, 0 )
#define macc_to_output_2(r, m)	macc_to_output( r, m, 2, 0 )
#define macc_to_output_3(r, m)	macc_to_output( r, m, 3, 0 )
#define macc_to_output_0s(r, m)	macc_to_output( r, m, 0, 1 )
#define macc_to_output_1s(r, m)	macc_to_output( r, m, 1, 1 )
#define macc_to_output_2s(r, m)	macc_to_output( r, m, 2, 1 )
#define macc_to_output_3s(r, m)	macc_to_output( r, m, 3, 1 )

static INT64 check_macc_overflow( int shift, int saturate )
{
	INT64 m = macc_read;
	UINT64 m1, mask;

	switch( shift )
	{
	case 0: mask = MACC_M1_0; break;
	case 1: mask = MACC_M1_1; break;
	case 2: mask = MACC_M1_2; break;
	default: return macc_read;
	}

	/* overflow detection */
	m1 = m & mask;
	if (m1 && m1 != mask)
	{
		st1 |= ST1_MOV;
		if (saturate)
		{
			if (m & MACC_SIGN)
				m = MACC_SATN;
			else
				m = MACC_SATP;
		}
	}
	return m;
}

#define check_macc_overflow_0()		check_macc_overflow( 0, 0 )
#define check_macc_overflow_1()		check_macc_overflow( 1, 0 )
#define check_macc_overflow_2()		check_macc_overflow( 2, 0 )
#define check_macc_overflow_3()		check_macc_overflow( 3, 0 )
#define check_macc_overflow_0s()	check_macc_overflow( 0, 1 )
#define check_macc_overflow_1s()	check_macc_overflow( 1, 1 )
#define check_macc_overflow_2s()	check_macc_overflow( 2, 1 )
#define check_macc_overflow_3s()	check_macc_overflow( 3, 1 )

static UINT32 get_cmem( UINT8 addr )
{
	if (sa == addr && update_counter_head != update_counter_tail)
		sti |= S_UPDATE;

	if (sti & S_UPDATE)
	{
		cmem[addr] = update[update_counter_tail];
		update_counter_tail = (update_counter_tail + 1) & 0x0f;
		update_empty();

		if (update_counter_head == update_counter_tail)
			sti &= ~S_UPDATE;

		return cmem[addr]; /* the value of crm is ignored during an update */
	}
	else
	{
		int crm = (st1 & ST1_CRM) >> ST1_CRM_SHIFT;
		UINT32 cvar = cmem[addr];
		if (crm == 1)
			return (cvar & 0xffff0000);
		else if (crm == 2)
			return (cvar << 16);
		return cvar;
	}
}

/* decoder (tms57kdec.cpp) */

static int xmode( UINT32 opcode, char type, cstate *cs )
{
	if (((opcode & 0x400) && (type == 'c')) || (!(opcode & 0x400) && (type == 'd')))
	{
		if (opcode & 0x100)
			return 0;
		else if (opcode & 0x80)
			cs->inc |= type == 'c' ? INC_CA : INC_ID;

		return 1;
	}
	else if (opcode & 0x200)
		cs->inc |= type == 'c' ? INC_CA : INC_ID;

	return 1;
}

static int sfao( UINT32 s1 ) { return s1 & ST1_SFAO ? 1 : 0; }
static int dbp( UINT32 s1 ) { return s1 & ST1_DBP ? 1 : 0; }
static int sfai( UINT32 s1 ) { return s1 & ST1_SFAI ? 1 : 0; }
static int sfmo( UINT32 s1 ) { return (s1 & ST1_SFMO) >> ST1_SFMO_SHIFT; }
static int rnd( UINT32 s1 )
{
	int rnd = (s1 & ST1_RND) >> ST1_RND_SHIFT;
	return rnd <= 4 ? rnd : 0;
}
static int movm( UINT32 s1 ) { return s1 & ST1_MOVM ? 1 : 0; }
static int sfma( UINT32 s1 ) { return (s1 & ST1_SFMA) >> ST1_SFMA_SHIFT; }

