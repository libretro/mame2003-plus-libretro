static UINT8		ym3438_int;			/* INT2 - from YM3438 */
static UINT8		scanline_int;		/* INT4 - programmable */
static UINT8		vblank_int;			/* INT6 - on every VBLANK */

/* System C/C2: bit 4 of I/O port H masks the H-INT (NULL on the other boards) */
