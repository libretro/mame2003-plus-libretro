/* execution */

static void execute_run( void )
{
	int ipc = -1;

	while(icount > 0 && !(sti & (S_IDLE | IN_PLOAD /*| IN_CLOAD*/)))
	{
		int iipc;

		if (ipc == -1)
			ipc = decode_get_pc();

		iipc = ipc;

		if (sti & (S_READ|S_WRITE))
		{
			if (sti & S_READ)
				xm_step_read();
			else
				xm_step_write();
		}

		macc_read = macc_write;
		macc_write = macc;

		for (;;)
		{
			const icd *i = cache.inst + ipc;

			ipc = i->next;
			switch (i->op)
			{
			case 0:
				goto inst;

			case 1:
				++ca;
				goto inst;

			case 2:
				++id;
				goto inst;

			case 3:
				++ca, ++id;
				goto inst;

#define CINTRPSWITCH
#include "tms57kops.h"
#undef CINTRPSWITCH

			default:
				goto inst;
			}
		}
	inst:
		icount--;

		if (rptc)
		{
			rptc--;
			ipc = iipc;
		}
		else if (sti & S_BRANCH)
		{
			sti &= ~S_BRANCH;
			ipc = -1;
		}
		else
		{
			pc++; /* wraps if it reaches 256, next wraps too */
			update_pc0();
		}

		if (rptc_next)
		{
			rptc = rptc_next;
			rptc_next = 0;
		}
	}

	if (icount > 0)
		icount = 0;
}

void tms57002dsp_sample( const INT32 *in, INT32 *out, int cycles )
{
	int n;
	int in_shift = ( st0 & ST0_SIM ) ? 8 : 0;

	/* sound_stream_update: in, out, then the sync starts the next period */
	for( n = 0; n < 4; n++ )
	{
		si[ n ] = ( (UINT32)in[ n ] << in_shift ) & 0xffffff;
		out[ n ] = (INT32)( so[ n ] << 8 ) >> 16;
	}
	sync_w( 1 );

	icount = cycles;
	execute_run();
}

void tms57002dsp_init( void )
{
	sti = S_IDLE;
	macc = macc_read = macc_write = 0;
	st0 = st1 = 0;
	txrd = 0;
	memset( cmem, 0, sizeof( cmem ) );
	memset( dmem0, 0, sizeof( dmem0 ) );
	memset( dmem1, 0, sizeof( dmem1 ) );
	memset( si, 0, sizeof( si ) );
	memset( so, 0, sizeof( so ) );
	memset( tms_pram, 0, sizeof( tms_pram ) );
	memset( tms_dram, 0, sizeof( tms_dram ) );
	memset( update, 0, sizeof( update ) );
	aacc = xoa = xba = xwr = xrd = creg = 0;
	hpc = 0;
	xm_adr = 0;
	allow_update = 0;
	unsupported_inst_warning = 0;
	cache_flush();
}

/* the 0.78 save states have no 64-bit type: the accumulators in halves */
static UINT32 macc_halves[ 6 ];

static void tms57002dsp_presave( void )
{
	macc_halves[ 0 ] = (UINT32)( (UINT64)macc >> 32 ); macc_halves[ 1 ] = (UINT32)macc;
	macc_halves[ 2 ] = (UINT32)( (UINT64)macc_read >> 32 ); macc_halves[ 3 ] = (UINT32)macc_read;
	macc_halves[ 4 ] = (UINT32)( (UINT64)macc_write >> 32 ); macc_halves[ 5 ] = (UINT32)macc_write;
}

static void tms57002dsp_postload( void )
{
	macc = (INT64)COMBINE_64_32_32( macc_halves[ 0 ], macc_halves[ 1 ] );
	macc_read = (INT64)COMBINE_64_32_32( macc_halves[ 2 ], macc_halves[ 3 ] );
	macc_write = (INT64)COMBINE_64_32_32( macc_halves[ 4 ], macc_halves[ 5 ] );
	/* the decode cache depends on the program: rebuilt */
	cache_flush();
}

